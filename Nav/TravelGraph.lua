-- Travel planner: how to get to the target. Dijkstra over
--   walking (straight lines on one continent at run speed, plus walking paths
--     learned from recordings, which are trusted more than straight lines),
--   flights between the flight masters this character knows,
--   boats, zeppelins, the Deeprun Tram (faction-filtered, timed by
--     Nav/Transit.lua when it knows the timetable) and walk-in portals,
--   the Hearthstone, when it is off cooldown and the bind location is a known
--     inn, and class teleports (Transit.Teleports); a ghost only walks.
-- The result is a list of legs; the arrow points at the current leg and
-- advances through them. Planning runs on target, zone, landing, bind and
-- hearth changes, never per frame, and is capped in nodes, pops and time.
--
-- Zone crossings (Nav.RegisterCrossings): on a continent with full crossing
-- data, walking between two zones goes only through a crossing (a pair of
-- waypoints at a tunnel, pass, bridge, gate or lift, with an arrival radius
-- and a caption per direction) or across an open-ground zone pair; inside a
-- zone it is straight lines as before. Approach-chain nodes past the mouth
-- link only to their chain neighbours, so a cave or climb is entered at its
-- mouth. Without crossing data every continent walks as before. Each leg
-- carries a caption and its waypoint's arrival radius; legs keep real
-- seconds (ETA) apart from the planning cost. The walk the arrow is on is
-- then followed along the walking engine's path (Nav/Walk.lua) and split
-- into steps at the chokepoints it passes (Travel.SplitWalk).
--
-- Walks into the target: on a continent the walking engine covers, the walks
-- from the places near the target (flight masters, docks and portal ends, the
-- bound inn, teleport landings, crossing ends, the player) are measured once
-- per target by the engine (Nav/Walk.lua Walk.Measure, priced for the
-- player's faction) instead of straight x1.25 (a place the engine finds no
-- walk from keeps its straight estimate): the router's cost chooses (a road
-- costs less than its yards, a slope or the other faction's town more), its
-- yards time the walk and measure the leg. When the measure comes in the
-- route is planned again and changes only if it now goes another way
-- (Travel.Remeasured). Every later walk leg takes the yards of its own
-- engine path once searched (Travel.PricePaths), and the other faction's
-- towns that path enters (leg.hubs: "Hostile town: <name>" in the journey,
-- said once by the arrow as the walk starts, Travel.TakeWarning). A straight
-- walk through zones far above the player costs more (Nav/Danger.lua, as the
-- engine prices its walks; never a time), and a planner rule may scale walk
-- costs too, never times (Travel.WalkCostHook).
--
-- Data comes from TravelData.lua (generated by `node tools/polestar.js
-- travel build`): Era flight masters and legs, transports, inns, learned
-- paths and crossings learned from recordings; full crossing data comes from
-- the optional local data addon Polestar_Travel.
--
-- Docks: a transport end is its ship's stop. A ship that lies in the water
-- off its pier has a board point on the deck (the end's `board`, from the
-- navigation grid): the dock is there, so the walk to the boat ends on the
-- deck (with the deck's height for the walking engine) and the boarding,
-- leaving and arrival checks (BOARD, LEAVE, DOCK_ARRIVE) measure from it; the
-- ride, its caption and its timetable stay the transport's.

