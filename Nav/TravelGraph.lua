-- `class`: a class's own flight node (Nighthaven: Bunthen Plainswind and Silva Fil'naveth fly Druids
-- only, out of Moonglade) is that class's alone, and needs no flight path learnt.
function allowed(mask, faction, class)
	if class then
		local C = ns.Compat
		local info = C and C.GetPlayerInfo and C.GetPlayerInfo()
		if not (info and info.class == class) then return false end
	end
	return mask == 3 or (faction ~= 0 and mask == faction)
end

function yards(c1, x1, y1, c2, x2, y2)
	if c1 ~= c2 then return huge end
	local dx, dy = x2 - x1, y2 - y1
	return sqrt(dx * dx + dy * dy)
end

-- The zone a point walks in on a continent with crossing data: its own map
-- when that is a zone the data knows, nil for a zone without crossing data
-- (walked as before), else the smallest known zone frame holding the point.
function zoneOf(map, c, wx, wy)
	if map then
		local z = zoneInfo[map]
		if z and z.c == c then return map end
		if wildZone[map] then return nil end
	end
	local best, area
	for m, z in pairs(zoneInfo) do
		if z.c == c then
			local h, w = z.bottom - z.top, z.right - z.left
			if h ~= 0 and w ~= 0 then
				local fy, fx = (wx - z.top) / h, (wy - z.left) / w
				if fx >= 0 and fx <= 1 and fy >= 0 and fy <= 1 then
					local a = h * w
					if a < 0 then a = -a end
					if not area or a < area or (a == area and m < best) then best, area = m, a end
				end
			end
		end
	end
	return best
end
Travel.ZoneOf = zoneOf

function pathZoneOf(i)
	local z = pathZone[i]
	if z == nil then
		z = zoneOf(pathMap[i], pathC[i], pathX[i], pathY[i]) or false
		pathZone[i] = z
	end
	return z or nil
end

-- May a straight walk go from zone a into zone b? (nil: no crossing data there)
function zonesWalk(a, b)
	if a == nil or b == nil or a == b then return true end
	local o = openPair[a]
	return o ~= nil and o[b] == true
end

function zoneName(map)
	local C = ns.Compat
	local name = C and C.GetMapName and C.GetMapName(map)
	if name then return name end
	local z = zoneInfo[map]
	return z and z.name or tostring(map)
end

-- The chain node past a mouth that a point is inside (within max(CAPTURE x radius, CAPTURE_MIN)), or nil.
-- A node with a floor height (z) holds only a point on that floor (z within 20 yd: the Undercity's entrance hall, not
-- the city under it); a point of unknown height, when one floor it may be on (`floors`: Walk.Floors) is within 20 yd
-- of it and none lies more than 20 yd below it (the hall and the gallery over it, never the city under it), or when
-- `loose` (a target: a map click), else not.
function onEvery(floors, h)
	if not floors or not floors[1] then return false end
	local near = false
	for _, f in ipairs(floors) do
		if h - f > 20 then return false end
		if f - h <= 20 then near = true end
	end
	return near
end
function insideChain(c, wx, wy, z, loose, floors)
	local best, bestD
	for _, ch in ipairs(chains) do
		local nodes = ch.nodes
		local last = ch.open == "both" and #nodes - 1 or #nodes
		for k = 2, last do
			local nd = nodes[k]
			local floorOK = not nd.z or (z and z - nd.z <= 20 and nd.z - z <= 20) or (z == nil and (loose or onEvery(floors, nd.z)))
			if nd.c == c and floorOK then
				local d = yards(c, wx, wy, nd.c, nd.wx, nd.wy)
				local cap = nd.r * CAPTURE
				if cap < CAPTURE_MIN then cap = CAPTURE_MIN end
				if d <= cap and (not bestD or d < bestD) then best, bestD = nd, d end
			end
		end
	end
	return best
end

-- Walking from crossing end `e` to its partner.
function crossCaption(e)
	return e.caption or format(L["Go to %s"], zoneName(e.partner.map))
end

